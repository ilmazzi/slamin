    public function searchEmojis()
    {
        // Search is handled by the computed property in the view
    }

    public function getFilteredEmojisProperty()
    {
        if (empty($this->searchQuery)) {
            return $this->emojiData[$this->selectedCategory] ?? $this->emojiData['smileys'];
        }

        $allEmojis = collect($this->emojiData)->flatten();
        
        return $allEmojis->filter(function ($emoji) {
            return str_contains($emoji, $this->searchQuery) || 
                   str_contains($this->getEmojiDescription($emoji), strtolower($this->searchQuery));
        })->take(50)->values();
    }

