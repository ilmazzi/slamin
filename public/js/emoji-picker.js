    initEmojiButtons() {
        const emojiButtons = document.querySelectorAll('.emoji-btn');
        emojiButtons.forEach(button => {
            button.addEventListener('click', (e) => {
                e.preventDefault();
                e.stopPropagation();
                this.toggleEmojiPicker(button.id);
            });
        });
    }

    toggleEmojiPicker(buttonId) {
        const picker = document.getElementById(`emoji-picker-${buttonId}`);

        if (this.activePicker && this.activePicker !== picker) {
            this.activePicker.classList.add('d-none');
        }

        if (picker.classList.contains('d-none')) {
            picker.classList.remove('d-none');
            this.activePicker = picker;
            this.loadEmojis('smileys', buttonId);
        } else {
            picker.classList.add('d-none');
            this.activePicker = null;
        }
    }

    closeAllPickers() {
        if (this.activePicker) {
            this.activePicker.classList.add('d-none');
            this.activePicker = null;
        }
    }

    loadEmojis(category, buttonId) {
        const grid = document.getElementById(`emoji-grid-${buttonId}`);
        const emojis = this.emojiData[category] || this.emojiData.smileys;

        grid.innerHTML = emojis.map(emoji => `
            <div class="emoji-item" onclick="emojiPicker.insertEmoji('${emoji}', '${buttonId}')">
                ${emoji}
            </div>
        `).join('');
    }

        insertEmoji(emoji, buttonId) {
        // Usa la funzione globale definita in chat-realtime.js
        if (window.insertQuickEmoji) {
            window.insertQuickEmoji(emoji);
        }

        this.closeAllPickers();
    }

    searchEmojis(query, buttonId) {
        if (!query.trim()) {
            this.loadEmojis('smileys', buttonId);
            return;
        }

        const allEmojis = Object.values(this.emojiData).flat();
        const filtered = allEmojis.filter(emoji =>
            emoji.includes(query) || this.getEmojiDescription(emoji).toLowerCase().includes(query.toLowerCase())
        );

        const grid = document.getElementById(`emoji-grid-${buttonId}`);
        grid.innerHTML = filtered.map(emoji => `
            <div class="emoji-item" onclick="emojiPicker.insertEmoji('${emoji}', '${buttonId}')">
                ${emoji}
            </div>
        `).join('');
    }

